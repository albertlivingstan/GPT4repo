def generate_follow_up_questions():
    """Generate follow-up questions for the user."""

    questions = [
        "When did your symptoms begin?",
        "Are your symptoms improving or worsening?",
        "What is your measured temperature, if you have a fever?",
        "Are you experiencing difficulty breathing?",
        "Is your cough dry or producing mucus?",
        "Do you have any relevant medical conditions?"
    ]

    return questions